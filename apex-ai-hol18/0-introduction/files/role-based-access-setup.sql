-- ============================================================================
-- LiveLab: TAP and ESS role-based access setup
--
-- Run this script once in SQL Workshop > SQL Scripts as the schema that owns
-- TMS_EMPLOYEES. It creates the role tables, seeds the four lab roles and demo
-- employees, assigns one role to each demo employee, and prepares the local
-- lab credentials. The role tables and TMS_EMPLOYEES.PASSWORD column must not
-- already exist in the schema.
--
-- Prerequisites:
--   * TMS_EMPLOYEES with EMPLOYEE_ID, FIRST_NAME, LAST_NAME, EMAIL, JOB_ID,
--     DEPT_ID, and STATUS columns.
--   * The job titles used below must exist in TMS_JOBS, and department IDs 2
--     and 3 must exist in the TMS sample data. Change those values if needed.
--
-- The demo addresses use the reserved .example domain. Existing rows matching
-- those addresses are deliberately refreshed as active lab accounts. All
-- active employees receive the lab password "apex". Oracle commits DDL
-- implicitly, so this is a one-time setup script rather than one transaction
-- that can be rolled back as a whole.
-- ============================================================================

-- The authentication steps in this LiveLab use STANDARD_HASH and do not need
-- DBMS_CRYPTO. If customized code calls DBMS_CRYPTO, a DBA can grant it
-- separately to the APEX parsing schema (replace APEX_LL if needed):
-- GRANT EXECUTE ON SYS.DBMS_CRYPTO TO APEX_LL;

-- Create the role lookup table.
CREATE TABLE tms_roles (
  role_id   NUMBER GENERATED BY DEFAULT AS IDENTITY,
  role_code VARCHAR2(30)  NOT NULL,
  role_name VARCHAR2(100) NOT NULL,
  is_active NUMBER(1)     DEFAULT 1 NOT NULL,
  CONSTRAINT pk_tms_roles PRIMARY KEY (role_id),
  CONSTRAINT uq_tms_roles_code UNIQUE (role_code),
  CONSTRAINT ck_tms_roles_active CHECK (is_active IN (0, 1))
);

-- Create the employee-to-role mapping table. The composite primary key
-- permits one row per employee and role.
CREATE TABLE tms_employee_roles (
  employee_id NUMBER        NOT NULL,
  role_id     NUMBER        NOT NULL,
  assigned_on TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  assigned_by VARCHAR2(255),
  is_active   NUMBER(1)     DEFAULT 1 NOT NULL,
  CONSTRAINT pk_tms_employee_roles
    PRIMARY KEY (employee_id, role_id),
  CONSTRAINT fk_ter_employee
    FOREIGN KEY (employee_id)
    REFERENCES tms_employees (employee_id),
  CONSTRAINT fk_ter_role
    FOREIGN KEY (role_id)
    REFERENCES tms_roles (role_id),
  CONSTRAINT ck_ter_is_active
    CHECK (is_active IN (0, 1))
);

CREATE INDEX ix_ter_role
  ON tms_employee_roles (role_id);

-- Seed the role catalog without duplicating role codes.
MERGE INTO tms_roles target
USING (
  SELECT 'RECRUITER' AS role_code, 'Recruiter' AS role_name FROM dual
  UNION ALL
  SELECT 'HR_ADMIN', 'HR Admin' FROM dual
  UNION ALL
  SELECT 'HIRING_MANAGER', 'Hiring Manager' FROM dual
  UNION ALL
  SELECT 'TA_ADMIN', 'TA Admin' FROM dual
) source
ON (target.role_code = source.role_code)
WHEN MATCHED THEN
  UPDATE SET target.role_name = source.role_name,
             target.is_active = 1
WHEN NOT MATCHED THEN
  INSERT (role_code, role_name, is_active)
  VALUES (source.role_code, source.role_name, 1);

-- Add the password column and create the hashing function.
ALTER TABLE tms_employees ADD password VARCHAR2(80);

CREATE OR REPLACE FUNCTION hash_password (
  p_user_name IN VARCHAR2,
  p_password  IN VARCHAR2
) RETURN VARCHAR2
IS
  l_salt     CONSTANT VARCHAR2(255) := '2345USFGOJN2T3HW89EFGOBN23R5SDFGAKL';
  l_password VARCHAR2(64);
BEGIN
  SELECT STANDARD_HASH(
           p_password || SUBSTR(l_salt, 4, 14) ||
           UPPER(p_user_name) || SUBSTR(l_salt, 5, 10),
           'SHA256'
         )
    INTO l_password
    FROM dual;

  RETURN l_password;
END hash_password;
/

-- Hash the plain-text password whenever it is inserted or changed.
CREATE OR REPLACE TRIGGER trg_tms_employees_hash_pwd
BEFORE INSERT OR UPDATE OF password ON tms_employees
FOR EACH ROW
BEGIN
  IF :NEW.password IS NOT NULL THEN
    :NEW.password := hash_password(:NEW.email, :NEW.password);
  END IF;
END;
/

-- Seed or refresh the demo accounts and assign the lab password to all active
-- employees. The trigger hashes the plain-text password before it is stored.
MERGE INTO tms_employees target
USING (
  WITH demo_people AS (
    SELECT 'maya.patel@acme.example' AS email,
           'Maya' AS first_name,
           'Patel' AS last_name,
           'HR Generalist' AS job_title,
           'Human Resources' AS dept_name
    FROM dual
    UNION ALL
    SELECT 'arjun.mehta@acme.example',
           'Arjun',
           'Mehta',
           'Payroll Specialist',
           'Human Resources'
    FROM dual
    UNION ALL
    SELECT 'olivia.brown@acme.example',
           'Olivia',
           'Brown',
           'DevOps Engineer',
           'Engineering'
    FROM dual
    UNION ALL
    SELECT 'liam.wilson@acme.example',
           'Liam',
           'Wilson',
           'HR Business Partner',
           'Human Resources'
    FROM dual
  ),
  employee_source AS (
    -- Existing active employees, excluding the demo accounts handled below.
    SELECT e.employee_id,
           e.first_name,
           e.last_name,
           e.email,
           e.job_id,
           e.dept_id,
           e.status,
           'apex' AS lab_password,
           'N' AS is_demo
    FROM tms_employees e
    WHERE e.status = 'Active'
      AND (
        e.email IS NULL
        OR UPPER(TRIM(e.email)) NOT IN (
          'MAYA.PATEL@ACME.EXAMPLE',
          'ARJUN.MEHTA@ACME.EXAMPLE',
          'OLIVIA.BROWN@ACME.EXAMPLE',
          'LIAM.WILSON@ACME.EXAMPLE'
        )
      )

    UNION ALL

    -- Demo accounts to insert or refresh.
    SELECT CAST(NULL AS NUMBER) AS employee_id,
           p.first_name,
           p.last_name,
           p.email,
           j.job_id,
           d.dept_id,
           'Active' AS status,
           'apex' AS lab_password,
           'Y' AS is_demo
    FROM demo_people p
    JOIN tms_jobs j
      ON UPPER(TRIM(j.title)) = UPPER(TRIM(p.job_title))
    JOIN tms_departments d
      ON UPPER(TRIM(d.name)) = UPPER(TRIM(p.dept_name))
  )
  SELECT employee_id,
         first_name,
         last_name,
         email,
         job_id,
         dept_id,
         status,
         lab_password,
         is_demo
  FROM employee_source
) source
ON (
     (source.is_demo = 'Y'
      AND UPPER(TRIM(target.email)) = UPPER(TRIM(source.email)))
  OR (source.is_demo = 'N'
      AND target.employee_id = source.employee_id)
)
WHEN MATCHED THEN
  UPDATE SET target.first_name = source.first_name,
             target.last_name  = source.last_name,
             target.job_id     = source.job_id,
             target.dept_id    = source.dept_id,
             target.status     = source.status,
             target.password  = source.lab_password
WHEN NOT MATCHED THEN
  INSERT (first_name, last_name, email, job_id, dept_id, status, password)
  VALUES (source.first_name, source.last_name, source.email,
          source.job_id, source.dept_id, source.status, source.lab_password)
  WHERE source.is_demo = 'Y';

-- Assign each demo account its workshop persona. Existing mappings are
-- reactivated without changing their original assignment timestamp.
MERGE INTO tms_employee_roles target
USING (
  SELECT e.employee_id,
         r.role_id
  FROM (
    SELECT 'maya.patel@acme.example' AS email,
           'RECRUITER' AS role_code
    FROM dual
    UNION ALL
    SELECT 'arjun.mehta@acme.example', 'HR_ADMIN' FROM dual
    UNION ALL
    SELECT 'olivia.brown@acme.example', 'HIRING_MANAGER' FROM dual
    UNION ALL
    SELECT 'liam.wilson@acme.example', 'TA_ADMIN' FROM dual
  ) demo
  JOIN tms_employees e
    ON UPPER(TRIM(e.email)) = UPPER(demo.email)
  JOIN tms_roles r
    ON r.role_code = demo.role_code
) source
ON (target.employee_id = source.employee_id
    AND target.role_id = source.role_id)
WHEN MATCHED THEN
  UPDATE SET target.is_active = 1,
             target.assigned_by = COALESCE(
               target.assigned_by,
               SYS_CONTEXT('USERENV', 'SESSION_USER')
             )
WHEN NOT MATCHED THEN
  INSERT (employee_id, role_id, assigned_by, is_active)
  VALUES (
    source.employee_id,
    source.role_id,
    SYS_CONTEXT('USERENV', 'SESSION_USER'),
    1
  );

COMMIT;