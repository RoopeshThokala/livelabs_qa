-- create audit log table
create table tms_audit_log (
    id               number         generated by default on null as identity
                                         constraint tms_audit_log_pk primary key,
    table_name           varchar2(255)  not null,
    operation            varchar2(50)   not null
                                         constraint tms_audit_log_op_ck
                                         check (operation in ('INSERT', 'UPDATE', 'DELETE')),
    old_values           clob,
    new_values           clob,
    changed_by           varchar2(255)  not null,
    changed_at           date           not null,
    row_version          integer        not null,
    created_on           date           not null,
    created_by           varchar2(255)  not null,
    updated_on           date           not null,
    updated_by           varchar2(255)  not null
)
/

-- trigger for audit log table
create or replace trigger tms_audit_log_biu
    before insert or update
    on tms_audit_log
    for each row
begin
    :new.updated_on := sysdate;
    :new.updated_by := coalesce(sys_context('APEX$SESSION', 'APP_USER'), user);
    if inserting then
        :new.row_version := 1;
        :new.created_on  := :new.updated_on;
        :new.created_by  := :new.updated_by;
        :new.changed_at  := :new.created_on;
    elsif updating then
        :new.row_version := nvl(:old.row_version, 0) + 1;
    end if;
end tms_audit_log_biu;
/